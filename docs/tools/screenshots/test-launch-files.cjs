// Run against build-ui.cjs and a dedicated headless Edge. UI_PORT/CDP_PORT override 5393/9334.
// Screenshots and assertion results stay in git-ignored out/.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

(async () => {
  const tabs = await (await fetch('http://127.0.0.1:' + (process.env.CDP_PORT || '9334') + '/json')).json();
  const origin = 'http://127.0.0.1:' + (process.env.UI_PORT || '5393');
  const tab = tabs.find(t => t.url.startsWith(origin)) || tabs.find(t => t.url === 'about:blank');
  const ws = new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise(resolve => ws.addEventListener('open', resolve, { once: true }));
  let seq = 0;
  const pending = new Map(), errors = [], checks = [], external = [];
  ws.addEventListener('message', e => {
    const message = JSON.parse(e.data);
    if (message.id) { const p = pending.get(message.id); pending.delete(message.id); message.error ? p.reject(message.error) : p.resolve(message.result); }
    if (message.method === 'Network.requestWillBeSent' && /^https?:/.test(message.params.request.url) && !message.params.request.url.startsWith(origin + '/')) external.push(message.params.request.url);
    if (message.method === 'Runtime.exceptionThrown') errors.push(message.params.exceptionDetails);
  });
  const send = (method, params = {}) => new Promise((resolve, reject) => {
    const id = ++seq; pending.set(id, { resolve, reject }); ws.send(JSON.stringify({ id, method, params }));
  });
  const evaluate = async expression => {
    const result = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true });
    if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails));
    return result.result.value;
  };
  const wait = async expression => {
    for (let i = 0; i < 100; i++) { if (await evaluate(expression)) return; await delay(50); }
    throw new Error('Timed out: ' + expression);
  };
  const visible = selector => `!!document.querySelector(${JSON.stringify(selector)})?.getClientRects().length`;
  const click = async selector => {
    await wait(visible(selector));
    const point = await evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); el.scrollIntoView({block:'center'}); const r=el.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`);
    await send('Input.dispatchMouseEvent', { type: 'mousePressed', button: 'left', clickCount: 1, ...point });
    await send('Input.dispatchMouseEvent', { type: 'mouseReleased', button: 'left', clickCount: 1, ...point });
  };
  const key = async (key, code = key, modifiers = 0) => {
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key, code, modifiers, text: key === 'Enter' ? '\r' : undefined, windowsVirtualKeyCode: key === 'Escape' ? 27 : key === 'Enter' ? 13 : undefined });
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key, code, modifiers });
  };
  const shot = async (name, selector) => {
    if (selector) await evaluate(`document.querySelector(${JSON.stringify(selector)}).scrollIntoView({block:'start'})`);
    else await evaluate('document.querySelector("main").scrollTop=0');
    await delay(80);
    const result = await send('Page.captureScreenshot', { format: 'png' });
    fs.writeFileSync(path.join(__dirname, 'out', 'launch-files-' + name + '.png'), Buffer.from(result.data, 'base64'));
  };
  const check = (name, actual, expected = true) => { assert.deepEqual(actual, expected, name); checks.push(name); };
  const textButton = async (text, scope = 'main') => {
    await evaluate(`(() => { const el=[...document.querySelectorAll(${JSON.stringify(scope + ' button')})].find(e=>e.textContent.trim().replace(/ +[0-9]+$/, '')===${JSON.stringify(text)}); if(!el) throw Error('Button not found: '+${JSON.stringify(text)}); el.click(); })()`);
    await delay(100);
  };
  const load = async (scenario = 'home') => {
    await send('Page.navigate', { url: origin + '/?shot=' + scenario });
    await wait('document.body?.dataset.ready === "1"');
  };
  const title = () => evaluate('document.querySelector("main h1")?.textContent.trim()');
  const list = () => evaluate('document.querySelector("[data-game-list]")?.textContent.trim()');
  const setLanguage = async lang => {
    await key(',', 'Comma', 2);
    await wait('!!Array.from(document.querySelectorAll("select")).find(el=>el.querySelector("option[value=en]"))');
    await evaluate(`(() => { const el=Array.from(document.querySelectorAll('select')).find(el=>el.querySelector('option[value=en]')); el.value=${JSON.stringify(lang)}; el.dispatchEvent(new Event('change',{bubbles:true})); })()`);
    await key('Escape');
    await delay(80);
  };
  const game = id => evaluate(`window.go.main.App.GetGames().then(rows=>rows.find(g=>g.id===${JSON.stringify(id)}))`);
  const config = value => evaluate(`Object.assign(window.__launchFilesMock, ${JSON.stringify(value)})`);
  const openGame = async id => { await click('main [data-game-id="' + id + '"] h3'); await wait(visible('[data-launch-details]')); await delay(70); };
  const menu = async () => { await click('[data-launch-menu]'); await wait(visible('[data-context-menu]')); };
  const edit = async () => { await menu(); await textButton('Edit', '[data-context-menu]'); await wait(visible('[data-launch-editor]')); };
  const rows = () => evaluate('[...document.querySelectorAll("[data-launch-edit-row]")].map(e=>({path:e.dataset.path,label:e.querySelector("input").value,primary:e.querySelector("[data-make-primary]").getAttribute("aria-pressed")==="true",placeholder:e.querySelector("input").placeholder}))');
  const save = async () => { await key('s', 'KeyS', 2); await wait(visible('[data-game-detail]')); await delay(80); };
  const exit = async () => { await key('Escape'); await wait('!document.querySelector("[data-game-detail]")'); };
  const setInput = (selector, value) => evaluate(`(() => {const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const find = async () => { await click('[data-launch-find]'); await wait(visible('[data-launch-candidates]')); await wait('!document.querySelector("[data-launch-candidates] [role=status]")'); };
  try {
    await send('Runtime.enable'); await send('Page.enable'); await send('Network.enable');
    await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1500, deviceScaleFactor: 1, mobile: false });
    await load('launch'); await openGame('g01');
    const original = await game('g01');
    check('Details lists primary and two extras', await evaluate('document.querySelectorAll("[data-launch-file]").length'), 3);
    check('automatic and custom labels', await evaluate('[...document.querySelectorAll("[data-launch-file]")].map(e=>e.textContent.trim())'), ['Game.exe', 'Configuration', 'Walkthrough']);
    check('no separate ellipsis', await evaluate('[...document.querySelectorAll("[data-game-right] button")].every(b=>b.getAttribute("aria-label")!=="More actions")'));
    await menu();
    check('menu file section matches Details', await evaluate('document.querySelectorAll("[data-launch-menu-file]").length'), 3);
    check('primary has accessible star label', await evaluate('document.querySelector("[data-launch-menu-file]").getAttribute("aria-label").startsWith("Primary file")'));
    check('old actions remain', await evaluate('["Edit", "Ignore when scanning", "Remove from launcher"].every(s=>document.querySelector("[data-context-menu]").textContent.includes(s))'));
    await wait('document.activeElement.hasAttribute("data-launch-menu-file")');
    check('keyboard focus starts in menu', await evaluate('document.activeElement.hasAttribute("data-launch-menu-file")'));
    await key('ArrowDown'); await key('Enter'); await delay(100);
    check('keyboard launches extra', await evaluate('window.__launchFilesMock.calls.at(-1).primary'), false);
    check('extra preserves recent launch', (await game('g01')).last_launched_at, original.last_launched_at);
    check('extra preserves playtime', (await game('g01')).time_played, original.time_played);
    await menu(); await key('Escape');
    check('Escape closes only menu', await evaluate('!!document.querySelector("[data-game-detail]") && !document.querySelector("[data-context-menu]")'));
    check('menu returns focus', await evaluate('document.activeElement.hasAttribute("data-launch-menu")'));
    await menu(); await send('Input.dispatchMouseEvent', {type:'mousePressed',button:'left',clickCount:1,x:300,y:100}); await send('Input.dispatchMouseEvent', {type:'mouseReleased',button:'left',clickCount:1,x:300,y:100});
    check('outside click closes menu', await evaluate('!document.querySelector("[data-context-menu]")'));
    await click('[data-main-play]'); await delay(100);
    check('Play targets main', await evaluate('window.__launchFilesMock.calls.at(-1).primary'));
    await click('[data-launch-file]:last-child'); await delay(100);
    check('Details opens guide without picker', await evaluate('window.__launchFilesMock.calls.at(-1).path.endsWith("guide.pdf")'));
    await setLanguage('ru');
    check('automatic label translates', await evaluate('document.querySelector("[data-launch-details]").textContent.includes("Прохождение")'));
    check('custom label stays literal', await evaluate('document.querySelector("[data-launch-details]").textContent.includes("Configuration")'));
    await setLanguage('en');
    await edit();
    const beforeEdit = await rows();
    await config({ selectedPath: '' }); await click('[data-launch-add]'); await delay(80);
    check('cancel native picker changes nothing', await rows(), beforeEdit);
    await config({ selectedPath: original.exec_path.replaceAll('/', '\\').toUpperCase() }); await click('[data-launch-add]'); await delay(80);
    check('manual duplicate rejected', await evaluate('document.querySelector("[data-launch-editor] [role=alert]").textContent'), 'Already added');
    await config({ selectedPath: original.folder_path + '/settings.exe' }); await click('[data-launch-add]'); await delay(100);
    check('manual add stays in draft', (await rows()).length, 4);
    check('draft has no DB write', (await game('g01')).launch_files.length, 2);
    await setInput('[data-launch-edit-row]:first-child input', 'My game');
    await setInput('[data-launch-edit-row]:nth-child(2) input', 'My settings');
    await click('[data-launch-edit-row]:nth-child(2) [data-make-primary]');
    const swapped = await rows();
    check('star swaps primary path and label', [swapped[0].path,swapped[0].label,swapped[1].path], [original.launch_files[0].path,'My settings',original.exec_path]);
    check('old primary label follows its path', swapped[1].label, 'My game');
    await save();
    check('Ctrl+S persists labels and swap', [(await game('g01')).exec_label,(await game('g01')).launch_files[0].path], ['My settings',original.exec_path]);
    await edit(); await setInput('[data-launch-edit-row]:first-child input', 'Discard me');
    await click('[data-launch-edit-row]:first-child [data-remove-file]');
    check('removal leaves no primary', await evaluate('!!document.querySelector("[data-no-primary]")'));
    await key('Escape'); await delay(80); await textButton('Discard', '.fixed');
    await wait(visible('[data-game-detail]'));
    check('Esc restores entire saved draft', (await game('g01')).exec_label, 'My settings');
    await exit(); await openGame('g01'); await edit();
    check('discarded label does not leak through library reopen', (await rows())[0].label, 'My settings');
    await key('Escape'); await wait(visible('[data-game-detail]'));
    await edit(); await click('[data-launch-edit-row]:first-child [data-remove-file]'); await save();
    check('saved removal does not promote', (await game('g01')).exec_path, '');
    await click('[data-main-play]'); await wait(visible('[data-launch-editor]'));
    check('Play without main opens file editor', await evaluate('!!document.querySelector("[data-no-primary]")'));
    await config({ selectedPath: original.folder_path + '/new-main.exe' }); await click('[data-launch-add]'); await delay(80);
    check('first added without main becomes main', (await rows())[0].path, original.folder_path + '/new-main.exe');
    await find();
    check('search candidates start unchecked', await evaluate('document.querySelectorAll("[data-launch-candidates] input:checked").length'), 0);
    check('candidate aliases deduplicated', await evaluate('document.querySelectorAll("[data-launch-candidates] input").length'), 4);
    check('already listed candidates disabled', await evaluate('document.querySelectorAll("[data-launch-candidates] input:disabled").length'), 3);
    await click('[data-launch-candidates] input:not(:disabled)');
    check('selection count visible', await evaluate('document.querySelector("[data-launch-selected]").textContent.startsWith("Selected: 1")'));
    await click('[data-launch-add-selected]');
    check('checked candidate appended to draft', (await rows()).some(f=>f.path.endsWith('walkthrough.html')));
    await save();
    check('discovery selection saved', (await game('g01')).launch_files.some(f=>f.path.endsWith('walkthrough.html')));
    await edit();
    await config({ error: true }); await find();
    check('search error has retry', await evaluate('!!document.querySelector("[data-launch-retry]")'));
    await config({ error: false, incomplete: true }); await click('[data-launch-retry]'); await wait(visible('[data-launch-incomplete]'));
    check('partial results explained', await evaluate('document.querySelector("[data-launch-incomplete]").textContent.includes("incomplete")'));
    await key('Escape');
    check('picker Escape keeps editor', await evaluate('!!document.querySelector("[data-launch-editor]") && !document.querySelector("[data-launch-candidates]")'));
    await config({ empty: true, incomplete: false }); await find();
    check('empty results explained', await evaluate('!!document.querySelector("[data-launch-empty]")'));
    await click('[data-launch-cancel]'); await config({ empty: false });
    await key('Escape'); await wait(visible('[data-game-detail]')); await exit();
    await openGame('g03'); await edit();
    check('capacity disables additions', await evaluate('document.querySelector("[data-launch-add]").disabled && document.querySelector("[data-launch-find]").disabled'));
    await click('[data-launch-edit-row]:last-child [data-remove-file]'); await find();
    await click('[data-launch-candidates] input:not(:disabled)');
    check('checkbox selection respects remaining capacity', await evaluate('document.querySelectorAll("[data-launch-candidates] input:not(:checked):not(:disabled)").length'), 0);
    await click('[data-launch-add-selected]'); await save();
    check('capacity retained on save', (await game('g03')).launch_files.length, 8);
    await exit(); await openGame('g07'); await edit();
    check('relink overflow retained', (await rows()).length, 11);
    await setInput('[data-launch-edit-row]:nth-child(2) input', 'Overflow label'); await save();
    check('overflow labels editable without truncation', [(await game('g07')).launch_files.length,(await game('g07')).launch_files[0].label], [10,'Overflow label']);
    await exit(); await openGame('g08'); await menu();
    check('single-file chevron still has actions but no file section', await evaluate('document.querySelectorAll("[data-launch-menu-file]").length'), 0);
    await key('Escape'); await exit(); await openGame('g05'); await menu();
    check('zero-file menu has no file section', await evaluate('document.querySelectorAll("[data-launch-menu-file]").length'), 0);
    await key('Escape'); await click('[data-launch-empty-edit]'); await wait(visible('[data-launch-editor]'));
    check('empty Details leads to editor', await evaluate('!!document.querySelector("[data-no-primary]")'));
    await key('Escape'); await wait(visible('[data-game-detail]')); await exit(); await openGame('g02');
    check('missing extra is muted and explained', await evaluate('document.querySelector("[data-launch-file]:last-child").textContent.includes("File not found") && document.querySelector("[data-launch-file]:last-child").classList.contains("text-slate-500")'));
    await click('[data-launch-file]:last-child'); await delay(80);
    check('missing extra reports localized error', await evaluate('document.body.innerText.includes("launch file not found") || document.body.innerText.includes("Launch file not found")'));
    await click('[data-main-play]'); await delay(80);
    check('missing extra does not block primary', await evaluate('window.__launchFilesMock.calls.at(-1).id === "g02" && window.__launchFilesMock.calls.at(-1).primary'));
    await exit(); await openGame('g04'); await click('[data-main-play]'); await delay(80);
    check('missing primary is not replaced with extra', await evaluate('window.__launchFilesMock.calls.at(-1).id !== "g04"'));

    // Late picker/discovery responses must not reopen UI after navigation, lock or panic.
    await exit(); await openGame('g01'); await edit();
    await config({ delay: 500, lateReply: true }); await click('[data-launch-find]'); await key('Escape'); await delay(600);
    check('cancel discards late discovery', await evaluate('!document.querySelector("[data-launch-candidates]")'));
    await click('[data-launch-find]'); await evaluate('window.__mockEmit("privacy-panic")'); await delay(600);
    check('panic discards discovery and editor', await evaluate('!document.querySelector("[data-launch-editor]") && !document.querySelector("[data-launch-candidates]")'));
    await openGame('g01'); await edit(); await click('[data-launch-find]'); await evaluate('window.__mockEmit("privacy-locked")'); await delay(600);
    check('lock discards discovery', await evaluate('!document.querySelector("[data-launch-editor]") && !document.querySelector("[data-launch-candidates]")'));
    await load('launch'); await openGame('g01'); await edit();
    await config({ selectDelay: 500, selectedPath: 'D:/Games/Late/config.exe', lateReply: true }); await click('[data-launch-add]'); await key('Escape'); await delay(600);
    check('late file dialog does not change saved list', (await game('g01')).launch_files.length, 2);
    await config({ availabilityDelay: 500 }); await click('[data-launch-menu]'); await key('Escape'); await delay(600);
    check('Escape cancels pending menu without leaving game', await evaluate('!!document.querySelector("[data-game-detail]") && !document.querySelector("[data-context-menu]")'));
    await click('[data-launch-menu]'); await evaluate('window.__mockEmit("privacy-panic")'); await delay(600);
    check('panic discards late availability/menu', await evaluate('!document.querySelector("[data-context-menu]") && !document.querySelector("[data-game-detail]")'));

    await load('launch'); await openGame('g01');
    await config({ availabilityDelay: 500 }); await click('[data-launch-menu]'); await key('ArrowLeft', 'ArrowLeft', 1); await delay(600);
    check('history navigation discards pending menu', await evaluate('!document.querySelector("[data-context-menu]") && !document.querySelector("[data-game-detail]")'));
    await config({ availabilityDelay: 0 }); await openGame('g02');
    check('new game has only its own files', await evaluate('document.querySelectorAll("[data-launch-file]").length'), 2);
    await exit(); await openGame('g01');
    await config({ availabilityError: true }); await click('[data-launch-menu]'); await wait(visible('[data-context-menu]')); await key('Escape');
    check('availability failure leaves paths and retry', await evaluate('!!document.querySelector("[data-launch-details] [role=alert]") && document.querySelectorAll("[data-launch-file]").length===3'));
    await config({ availabilityError: false }); await textButton('Retry', '[data-launch-details]');
    check('availability retry clears error', await evaluate('!document.querySelector("[data-launch-details] [role=alert]")'));
    await evaluate('document.querySelector("main").scrollTop=0'); await delay(100);
    const rect = await evaluate('(() => {const r=document.querySelector("[data-game-right]").getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height,scale:1};})()');
    const right = await send('Page.captureScreenshot', {format:'png',clip:rect,captureBeyondViewport:true});
    fs.writeFileSync(path.join(__dirname,'out','launch-files-right.png'),Buffer.from(right.data,'base64'));
    await menu(); await shot('menu'); await key('Escape'); await edit(); await find(); await shot('editor');
    await key('Escape'); await key('Escape'); await wait(visible('[data-game-detail]'));
    await setLanguage('ru');
    await send('Emulation.setDeviceMetricsOverride', {width:900,height:1100,deviceScaleFactor:1,mobile:false});
    await shot('narrow-ru');
    check('narrow layout has no horizontal overflow', await evaluate('document.querySelector("main").scrollWidth <= document.querySelector("main").clientWidth'));
    await menu();
    check('narrow menu stays inside viewport', await evaluate('(() => {const r=document.querySelector("[data-context-menu]").getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.top>=0 && r.bottom<=innerHeight;})()'));
    await key('Escape'); await setLanguage('en'); await edit(); await setLanguage('ru');
    await wait('[...document.querySelectorAll("[data-launch-label]")].some(e=>e.placeholder==="Прохождение")');
    check('editor automatic placeholders translate', await evaluate('[...document.querySelectorAll("[data-launch-label]")].some(e=>e.placeholder==="Прохождение")'));
    check('editor explicit labels do not translate', (await rows())[1].label, 'Configuration');
    await shot('editor-narrow-ru', '[data-launch-editor]');
    check('narrow editor has no horizontal overflow', await evaluate('document.querySelector("main").scrollWidth <= document.querySelector("main").clientWidth'));
    await setLanguage('en'); await key('Escape'); await wait(visible('[data-game-detail]'));
    await send('Emulation.setDeviceMetricsOverride', {width:1440,height:1500,deviceScaleFactor:1,mobile:false});
    await load('find');
    check('no uncaught browser errors', errors, []);
    check('no external network requests', external, []);
    fs.writeFileSync(path.join(__dirname,'out','launch-files-checks.json'),JSON.stringify({checks,rightColumn:rect},null,2));
    console.log('PASS: ' + checks.length + ' launch file UI checks');
  } catch (err) {
    console.error(err);
    const result = await send('Page.captureScreenshot', {format:'png'});
    fs.writeFileSync(path.join(__dirname,'out','launch-files-failure.png'),Buffer.from(result.data,'base64'));
    process.exitCode=1;
  } finally { ws.close(); }
})();
